-- リクエストヘッダーの招待コード（PostgREST が request.headers に設定する）
create or replace function public.request_invite_code()
returns text
language sql
stable
as $$
  select nullif(coalesce(current_setting('request.headers', true), '{}')::json->>'x-invite-code', '');
$$;

-- リクエスト元のIPアドレス（前段のプロキシが付けるヘッダー。取得できなければ null）
create or replace function public.request_client_ip()
returns text
language sql
stable
as $$
  select nullif(btrim(coalesce(
    h->>'cf-connecting-ip',
    split_part(h->>'x-forwarded-for', ',', 1),
    h->>'x-real-ip'
  )), '')
  from (select coalesce(current_setting('request.headers', true), '{}')::json as h) t;
$$;

-- 閲覧できるか: 管理者（is_admin）または 有効期限内で取り消されていない招待コード
create or replace function public.can_view()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.is_admin()
      or exists (
        select 1 from public.invites
        where code = public.request_invite_code()
          and revoked_at is null
          and expires_at > now()
      );
$$;

-- 招待コードの確認（有効なら最終アクセス・回数・アクセス履歴を記録し、自動延長する）
-- 自動延長: auto_extend_days が設定されていれば、有効期限を「今から auto_extend_days 日後」まで延ばす
create or replace function public.redeem_invite(p_code text)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_invite record;
  v_headers json := coalesce(current_setting('request.headers', true), '{}')::json;
begin
  update public.invites
  set last_used_at = now(),
      use_count = use_count + 1,
      expires_at = case
        when auto_extend_days is not null
          then greatest(expires_at, now() + make_interval(days => auto_extend_days))
        else expires_at
      end
  where code = p_code and revoked_at is null and expires_at > now()
  returning id, label, expires_at into v_invite;

  if not found then
    return json_build_object('valid', false);
  end if;

  insert into public.invite_access_logs (invite_id, ip, user_agent)
  values (v_invite.id, public.request_client_ip(), left(v_headers->>'user-agent', 300));
  delete from public.invite_access_logs
  where invite_id = v_invite.id and accessed_at < now() - interval '90 days';

  return json_build_object('valid', true, 'label', v_invite.label, 'expires_at', v_invite.expires_at);
end;
$$;

