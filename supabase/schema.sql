-- 13-3. 申請者による編集（メモ・枚数・カードの削除）。編集履歴もここで記録する
-- Q-2026-11-06-3: メモ1000文字・枚数変更と削除はそれぞれ200件まで
drop function if exists public.edit_request_by_token(text, text, jsonb);
create or replace function public.edit_request_by_token(
  p_token text,
  p_message text default null,
  p_item_changes jsonb default null,
  p_remove_item_ids bigint[] default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_req record;
  v_change jsonb;
  v_old record;
  v_qty integer;
  v_new_message text;
  v_remove_id bigint;
begin
  if not public.can_view() then
    raise exception '招待リンクが無効か、有効期限が切れています' using errcode = '42501';
  end if;
  if p_message is not null and char_length(btrim(p_message)) > 1000 then
    raise exception 'メモは1000文字以内で入力してください' using errcode = '22023';
  end if;
  if p_item_changes is not null and (jsonb_typeof(p_item_changes) <> 'array' or jsonb_array_length(p_item_changes) > 200) then
    raise exception '一度に変更できるのは200件までです' using errcode = '22023';
  end if;
  if coalesce(array_length(p_remove_item_ids, 1), 0) > 200 then
    raise exception '一度に削除できるのは200件までです' using errcode = '22023';
  end if;
  select id, requester_name, message, status into v_req
  from public.requests where token::text = p_token
  for update;
  if not found then
    raise exception '編集用リンクが無効です' using errcode = '42501';
  end if;
  if v_req.status <> 'pending' then
    raise exception '受付中のリクエストのみ編集できます' using errcode = '22023';
  end if;

  if p_message is not null then
    v_new_message := nullif(btrim(p_message), '');
    if v_new_message is distinct from v_req.message then
      update public.requests set message = v_new_message where id = v_req.id;
      insert into public.request_edit_logs (request_id, editor_name, field_changed, old_value, new_value)
      values (v_req.id, v_req.requester_name, 'メモ', v_req.message, v_new_message);
    end if;
  end if;

  if p_item_changes is not null then
    for v_change in select * from jsonb_array_elements(p_item_changes) loop
      v_qty := (v_change->>'quantity')::integer;
      if v_qty is null or v_qty < 1 then
        raise exception '枚数は1以上で指定してください' using errcode = '22023';
      end if;

      select ri.id, ri.quantity, coalesce(i.name, s.name, '不明') as name into v_old
      from public.request_items ri
      left join public.items i on i.id = ri.item_id
      left join public.supplies s on s.id = ri.supply_id
      where ri.id = (v_change->>'request_item_id')::bigint and ri.request_id = v_req.id;
      if not found then
        raise exception '対象のカードがこのリクエストに見つかりません' using errcode = '22023';
      end if;

      if v_old.quantity <> v_qty then
        update public.request_items set quantity = v_qty where id = v_old.id;
        insert into public.request_edit_logs (request_id, editor_name, field_changed, old_value, new_value)
        values (v_req.id, v_req.requester_name, '数量',
                v_old.name || ': ' || v_old.quantity || '枚', v_old.name || ': ' || v_qty || '枚');
      end if;
    end loop;
  end if;

  if p_remove_item_ids is not null and array_length(p_remove_item_ids, 1) > 0 then
    -- すべてのカードを削除することはできない（その場合はキャンセルを依頼してもらう）
    if not exists (
      select 1 from public.request_items
      where request_id = v_req.id and not (id = any(p_remove_item_ids))
    ) then
      raise exception 'すべてのカードは削除できません。リクエスト自体を取り消す場合は管理者に連絡してください' using errcode = '22023';
    end if;

    foreach v_remove_id in array p_remove_item_ids loop
      select ri.id, ri.quantity, coalesce(i.name, s.name, '不明') as name into v_old
      from public.request_items ri
      left join public.items i on i.id = ri.item_id
      left join public.supplies s on s.id = ri.supply_id
      where ri.id = v_remove_id and ri.request_id = v_req.id;
      if not found then
        raise exception '対象のカードがこのリクエストに見つかりません' using errcode = '22023';
      end if;

      delete from public.request_items where id = v_old.id;
      insert into public.request_edit_logs (request_id, editor_name, field_changed, old_value, new_value)
      values (v_req.id, v_req.requester_name, '削除', v_old.name || ': ' || v_old.quantity || '枚', null);
    end loop;
  end if;

  return v_req.id;
end;
$$;

-- 13-4. 申請者によるバリアント変更（同名カードの別型番・別レアリティへの差し替えのみ）
create or replace function public.swap_request_item_by_token(p_token text, p_request_item_id bigint, p_new_item_id bigint)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_req record;
  v_old record;
  v_new record;
begin
  if not public.can_view() then
    raise exception '招待リンクが無効か、有効期限が切れています' using errcode = '42501';
  end if;
  select id, requester_name, status into v_req
  from public.requests where token::text = p_token
  for update;
  if not found then
    raise exception '編集用リンクが無効です' using errcode = '42501';
  end if;
  if v_req.status <> 'pending' then
    raise exception '受付中のリクエストのみ編集できます' using errcode = '22023';
  end if;

  select ri.id, i.name, i.card_id, i.rarity into v_old
  from public.request_items ri
  join public.items i on i.id = ri.item_id
  where ri.id = p_request_item_id and ri.request_id = v_req.id;
  if not found then
    raise exception '対象のカードがこのリクエストに見つかりません' using errcode = '22023';
  end if;

  select id, card_id, rarity into v_new
  from public.items where id = p_new_item_id and name = v_old.name;
  if not found then
    raise exception '同じカードの別バリアントのみ選択できます' using errcode = '22023';
  end if;

  update public.request_items set item_id = v_new.id where id = v_old.id;
  insert into public.request_edit_logs (request_id, editor_name, field_changed, old_value, new_value)
  values (v_req.id, v_req.requester_name, 'カード変更',
          v_old.name || ' ' || coalesce(v_old.card_id, '') || ' ' || coalesce(v_old.rarity, ''),
          v_old.name || ' ' || coalesce(v_new.card_id, '') || ' ' || coalesce(v_new.rarity, ''));

  return v_req.id;
end;
$$;

-- 13-6. 管理者によるカード変更（D8。差し替え・枚数変更・編集履歴・完了済みなら在庫の差分と在庫ログを1つのトランザクションで行う）
-- Q-2026-11-06-5: 以前は画面から順に呼んでいたため、途中で失敗すると在庫と明細が食い違った。失敗すれば何も変わらない
-- 変更先は同じカード名の別型番・別レアリティのみ。在庫は increment_stock と同じく 0 未満にしない
create or replace function public.change_request_item_as_admin(p_request_item_id bigint, p_new_item_id bigint, p_quantity integer)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_req record;
  v_ri record;
  v_old record;
  v_new record;
  v_adj record;
  v_stock integer;
begin
  if not public.is_admin() then
    raise exception '権限エラー: 管理者のみ実行できます' using errcode = '42501';
  end if;
  if p_quantity is null or p_quantity < 1 then
    raise exception '枚数は1以上で指定してください' using errcode = '22023';
  end if;

  select ri.id, ri.request_id, ri.item_id, ri.quantity into v_ri
  from public.request_items ri where ri.id = p_request_item_id
  for update;
  if not found then
    raise exception '対象のカードがリクエストに見つかりません' using errcode = '22023';
  end if;
  if v_ri.item_id is null then
    raise exception 'カードの明細だけ変更できます' using errcode = '22023';
  end if;
  select r.id, r.status into v_req from public.requests r where r.id = v_ri.request_id for update;

  select i.id, i.name, i.card_id, i.rarity into v_old from public.items i where i.id = v_ri.item_id;
  if not found then
    raise exception '元のカードが見つかりません（削除された可能性があります）' using errcode = '22023';
  end if;
  select i.id, i.name, i.card_id, i.rarity into v_new from public.items i where i.id = p_new_item_id;
  if not found or v_new.name is distinct from v_old.name then
    raise exception '同じカードの別型番・別レアリティのみ選択できます' using errcode = '22023';
  end if;

  if v_new.id = v_old.id and p_quantity = v_ri.quantity then
    return v_req.id;  -- 変更なし
  end if;

  update public.request_items set item_id = v_new.id, quantity = p_quantity where id = v_ri.id;

  if v_new.id <> v_old.id then
    insert into public.request_edit_logs (request_id, editor_name, field_changed, old_value, new_value)
    values (v_req.id, '管理者', 'カード変更',
            v_old.name || ' ' || coalesce(v_old.card_id, '') || ' ' || coalesce(v_old.rarity, ''),
            v_new.name || ' ' || coalesce(v_new.card_id, '') || ' ' || coalesce(v_new.rarity, ''));
  end if;
  if p_quantity <> v_ri.quantity then
    insert into public.request_edit_logs (request_id, editor_name, field_changed, old_value, new_value)
    values (v_req.id, '管理者', '数量', v_old.name || ': ' || v_ri.quantity || '枚', v_new.name || ': ' || p_quantity || '枚');
  end if;

  -- 完了済みなら、元のカードの在庫を戻し、変更先の在庫を減らす（同じカードなら枚数の差分だけ）。行は id 順にロックする
  if v_req.status = 'completed' then
    for v_adj in
      select a.item_id, sum(a.delta)::integer as delta
      from (values (v_old.id, v_ri.quantity), (v_new.id, -p_quantity)) as a(item_id, delta)
      group by a.item_id
      having sum(a.delta) <> 0
      order by a.item_id
    loop
      update public.items
      set stock = greatest(0, stock + v_adj.delta), updated_at = now()
      where id = v_adj.item_id
      returning stock into v_stock;
      insert into public.stock_logs (item_id, delta, stock_after, source, request_id, note)
      values (v_adj.item_id, v_adj.delta, v_stock, 'request', v_req.id, '完了済みリクエストの編集');
    end loop;
  end if;

  return v_req.id;
end;
$$;
revoke execute on function public.change_request_item_as_admin(bigint, bigint, integer) from public, anon;
grant execute on function public.change_request_item_as_admin(bigint, bigint, integer) to authenticated;

-- 13-5. 未ログイン(anon)はリクエストを直接書き換えられないようにし、トークン列・管理者メモ列も見えないようにする
