    or exists (select 1 from public.stock_logs sl where sl.item_id = f.id));
  if bad is not null then raise exception '削除する行に在庫か参照があるので中止: %', left(bad, 1500); end if;

  select string_agg(distinct f.new_rarity, ', ') into bad from pg_temp._nfix f
  where f.action = 'rewrite' and not exists (
    select 1 from public.config c, jsonb_array_elements_text(c.value) v where c.key = 'rarities' and v = f.new_rarity);
  if bad is not null then raise exception 'レアリティ設定（config.rarities）にないコードがあるので中止: %', bad; end if;

  -- 1. 書き換え（レアリティだけ。行の id・在庫・参照はそのまま）
  insert into maintenance.rarity_fix_log (batch, step, item_id, old_rarity, new_rarity, old_name, new_name)
  select 'nfix-2026-11-14', 'rewrite', i.id, i.rarity, f.new_rarity, i.name, i.name
  from pg_temp._nfix f join public.items i on i.id = f.id where f.action = 'rewrite';
  update public.items i set rarity = f.new_rarity from pg_temp._nfix f where i.id = f.id and f.action = 'rewrite';

  -- 2. 削除（在庫0・参照なしを確認済み。戻せるよう元の行を丸ごと記録する）
  insert into maintenance.rarity_fix_log (batch, step, item_id, old_rarity, old_name, stock_moved, old_row)
  select 'nfix-2026-11-14', 'delete', i.id, i.rarity, i.name, 0,
         jsonb_build_object('id', i.id, 'name', i.name, 'card_id', i.card_id, 'rarity', i.rarity,
                            'stock', i.stock, 'category', i.category, 'updated_at', i.updated_at)
  from pg_temp._nfix f join public.items i on i.id = f.id where f.action = 'delete';
  delete from public.items i using pg_temp._nfix f where i.id = f.id and f.action = 'delete';

  -- 3. 最後の確認（合わなければ全部取り消す）
  select count(*), coalesce(sum(stock), 0) into n_now, s_now from public.items;
  if n_now <> n_before - n_del then raise exception '行数が合わない: 変更前 % − 削除 % ≠ 変更後 %', n_before, n_del, n_now; end if;
  if s_now <> s_before then raise exception '在庫合計が合わない: 変更前 % ≠ 変更後 %', s_before, s_now; end if;
  if exists (select 1 from public.items i join pg_temp._nfix f on f.id = i.id where f.action = 'rewrite' and i.rarity = 'N') then
    raise exception '書き換えた行に N が残っている';
  end if;
  if (select count(*) from maintenance.rarity_fix_log where batch = 'nfix-2026-11-14') <> n_del + n_rw then
    raise exception '記録の件数が合わない';
  end if;
  select string_agg(k, ' / ') into dup from (
    select coalesce(nullif(i.card_id, ''), i.name) || ' ' || i.rarity || ' ' || coalesce(i.category, '') as k
    from public.items i
    where (coalesce(nullif(i.card_id, ''), i.name), i.rarity, i.category) in (
      select coalesce(nullif(j.card_id, ''), j.name), j.rarity, j.category from public.items j join pg_temp._nfix f on f.id = j.id where f.action = 'rewrite')
    group by coalesce(nullif(i.card_id, ''), i.name), i.rarity, i.category having count(*) > 1) t;
  if dup is not null then raise exception '新しく重複ができた: %', left(dup, 1500); end if;

  drop table pg_temp._nfix;
  raise notice '完了: 書き換え %、削除 %、行数 % → %、在庫合計 %（変わらず）', n_rw, n_del, n_before, n_now, s_now;
end
$body$;

